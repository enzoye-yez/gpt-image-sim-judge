V4_WEIGHT_SECONDARY = 0.15


def v4_total(scores):
    """rate-v4 total from the seven single-dimension scores (0-10 each) -> 0-10.
    total = main^0.85 * secondary^0.15 - 1 with main = geometric mean of (content, text, arrangement, style) + 1 and
    secondary = mean of (color, lighting, detail) + 1 (the +1 lets a 0 score take part). Fixed before the human test."""
    import math
    main = math.exp(sum(math.log(float(scores[d]) + 1) for d in V4_MAIN) / len(V4_MAIN))
    sec = sum(float(scores[d]) + 1 for d in V4_SECONDARY) / len(V4_SECONDARY)
    return main ** (1 - V4_WEIGHT_SECONDARY) * sec ** V4_WEIGHT_SECONDARY - 1


