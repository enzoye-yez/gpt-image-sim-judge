"""GPT pairwise image-similarity judge.

Given two images, ask a GPT model how similar they look to a person, and get back 0-10 scores.

  rate-v3 (default): image_a = REFERENCE, image_b = CANDIDATE; seven dimensions content / lighting_color / composition /
           layout / style / detail / text, each with a one-sentence justification, plus a holistic overall; strict JSON schema.
  rate-v2: the earlier symmetric prompt (content / layout / color / style / text + overall + reason).

Online (concurrent, resumable):
    python sim_judge.py run pairs.jsonl out.jsonl [--prompt rate-v3] [--model gpt-6.1-terra] [--effort low] [--concurrency 16]
Batch API (half price, up to 24 h):
    python sim_judge.py batch-build pairs.jsonl work/ [--prompt ...]   # writes work/in/*.jsonl shards (< 180 MB each)
    python sim_judge.py batch-submit work/                            # uploads + creates one batch per shard
    python sim_judge.py batch-poll work/                              # downloads finished outputs to work/out/
    python sim_judge.py batch-collect work/ out.jsonl                 # parses outputs into the same rows as `run`

Input, one pair per line: {"pid": str, "image_a": path-or-URL, "image_b": path-or-URL}   (pid unique)
Output (rate-v3): {"pid", "score", "content", "lighting_color", "composition", "layout", "style", "detail", "text", "overall", "overall_calc",
                   "justifications": {dim: str}, "prompt", "model", "usage"}   (layout / text may be null; failures get "error")
The API key comes from $OPENAI_API_KEY (or the file in $OPENAI_API_KEY_FILE); it is never printed or written.
"""
import argparse, base64, concurrent.futures as cf, io, json, os, sys, threading, time
from functools import lru_cache
from pathlib import Path

import httpx
from PIL import Image

API = 'https://api.openai.com/v1'
DEFAULT_MODEL = 'gpt-6.1-terra'
MAX_SIDE = 1024          # images are downscaled so the long side is <= 1024 px
WEBP_QUALITY = 90
MAX_SHARD_BYTES = 180 * 2 ** 20   # Batch API input files must stay under 200 MB

# ---------------------------------------------------------------- prompts
# rate-v2 (2026-11-19): symmetric, 5 aspects + free overall. Kept byte-identical to the run behind the README numbers.
PROMPT_V2 = """You compare two images that were generated by an image model from design briefs. Judge how similar the two images look to a person, the way a designer would judge whether two renders are "the same design". Differences a viewer would not notice at a glance (fine texture, tiny details, slight shifts) should barely matter; differences in what is shown, how it is arranged, its colors, or its text should.
Score each aspect 0-10 (10 = indistinguishable, 0 = nothing in common):
- content: the subjects, objects and scene that are depicted; for charts, diagrams and data graphics this includes the data, trends and chart type
- layout: composition and where things are placed
- color: color palette and overall tone
- style: medium, rendering style, lighting, typography style
- text: the visible text, both the words and where/how large they appear; null if neither image has readable text
Then give an overall similarity 0-10 with these anchors: 10 essentially the same image; 8 same design with minor differences; 6 same subject and similar layout/style but clearly noticeable differences; 4 same topic but a different composition or a different color/style; 2 only loosely related; 0 unrelated.
Return only JSON: {"content": n, "layout": n, "color": n, "style": n, "text": n or null, "overall": n, "reason": "one short sentence"}"""

# rate-v3 (2026-11-24, final): REFERENCE vs CANDIDATE, seven design dimensions (Qwen-Image-PE lighting / composition / layout / detail,
# plus content, style and text), PRISM-style "start at 10 and deduct" bands, VQA-style "each difference counts in one dimension only",
# justification before score, strict JSON schema.
PROMPT_V3 = """You compare a CANDIDATE image against a REFERENCE image. Both were generated by image models from design briefs for the same request. Judge how closely the CANDIDATE reproduces the REFERENCE's design, the way a designer checks a render against an approved reference. Judge only what is visible.

Differences a viewer would not notice at a glance (fine noise, compression, a shift of a few pixels) should barely matter. Every other visible difference costs points.

Score seven dimensions. For each dimension, start at 10 and deduct for every difference you find in that dimension, using the bands below (several differences add up; the minimum is 0). First write a one-sentence justification naming the differences that cost points (or "no visible difference"), then give the integer score.

Judge every dimension independently, and count each difference only in the dimension it belongs to. For example, a recolored but otherwise identical image loses points in lighting_color only; a blurrier copy loses points in detail only; the same scene re-rendered as a flat illustration instead of a photo loses points in style (and detail) but not in content; a mirrored copy loses points in composition (and layout, if it has text blocks) but not in content.

1. content - what is depicted: subjects, objects, scene and their key attributes (kind, count, pose, clothing, props, actions). For charts, diagrams, infographics and UI: chart type, data values, trends, icons and content modules.
   - A main subject, object or scene element is missing, replaced or of a different kind (e.g. a cat instead of a dog, a different product): -6 to -8
   - Same main subjects, but key attributes differ (count, pose, clothing, action, chart type, data trend): -3 to -5
   - Secondary elements added, missing or changed: -1 to -2

2. lighting_color - color and light: palette, dominant and accent colors, saturation, color temperature, brightness and contrast, overall tone, light direction, shadows, highlights, reflections and material sheen. For flat graphics: palette, fills, gradients and shading treatment.
   - Different palette or overall tone (warm vs cool, dark vs light, day vs night), or light clearly from a different direction: -5 to -7
   - Same palette family, but noticeably different hues, saturation, brightness or contrast, or different shadow/highlight treatment: -2 to -4
   - A slight shift that is visible side by side: -1

3. composition - how the picture is framed: subject placement and scale, focal point, viewpoint and camera angle, framing and crop, balance, depth layering (foreground / background).
   - Different viewpoint, framing or focal subject, the main subject in a clearly different place or scale, or a mirrored arrangement: -5 to -7
   - Same arrangement, but noticeably different scale, crop or position of the main elements: -2 to -4
   - Slightly different spacing or balance: -1

4. layout - how text blocks, graphics and content modules are arranged: grid, alignment, spacing, whitespace, typographic hierarchy (which text is largest) and reading order. Use null if neither image has text blocks or designed modules (e.g. a plain photo or illustration).
   - Different module structure or reading order (e.g. title on top vs at the side, one column vs two, modules missing or added): -5 to -7
   - Same structure, but different alignment, spacing, block sizes or hierarchy: -2 to -4
   - Slight offsets or spacing changes: -1

5. style - the visual style as a whole: medium and rendering style (photo, 3D render, flat vector, painting, line art, collage), art direction and aesthetic (minimal, retro, editorial, cartoon, luxury), and the mood that style creates.
   - Different medium or rendering style (e.g. photo vs illustration, 3D vs flat): -6 to -8
   - Same medium, but a clearly different art direction or aesthetic (e.g. minimal vs ornate, cartoon vs realistic illustration): -3 to -5
   - Same style with a slightly different treatment or finish: -1 to -2

6. detail - the fine structure within the same style: material textures, local structures, environmental and background details, decorative and informational elements, sharpness.
   - Clearly different textures, level of detail, or background / decorative elements: -3 to -5
   - A few small details added, missing or changed: -1 to -2
   - Only lower sharpness or resolution (the same image, blurrier): -1 to -2

7. text - the visible words: their content and spelling, position, size and typeface style. Use null only if neither image has readable text; if only one image has text, score it.
   - Text missing in the CANDIDATE, or substantially different words: -6 to -8
   - Same text elements, but some words wrong, missing or added, or text in a clearly different position or size: -3 to -5
   - Different typeface style, or a few wrong characters: -1 to -2

Finally give an overall similarity 0-10 for the whole image with these anchors: 10 essentially the same image; 8 same design with minor differences; 6 same subject and similar layout/style but clearly noticeable differences; 4 same topic but a different composition or a different color/style; 2 only loosely related; 0 unrelated.

Return only the JSON object required by the schema."""

DIMS_V3 = ('content', 'lighting_color', 'composition', 'layout', 'style', 'detail', 'text')
NULLABLE_V3 = ('layout', 'text')


def _dim_schema(nullable):
    return {'type': 'object', 'additionalProperties': False, 'required': ['justification', 'score'],
            'properties': {'justification': {'type': 'string'},
                           'score': {'type': ['integer', 'null'] if nullable else 'integer', 'minimum': 0, 'maximum': 10}}}


SCHEMA_V3 = {'type': 'json_schema', 'name': 'image_similarity_v3', 'strict': True,
             'schema': {'type': 'object', 'additionalProperties': False, 'required': list(DIMS_V3) + ['overall'],
                        'properties': {**{d: _dim_schema(d in NULLABLE_V3) for d in DIMS_V3}, 'overall': _dim_schema(False)}}}

PROMPTS = {'rate-v2': PROMPT_V2, 'rate-v3': PROMPT_V3}
DEFAULT_PROMPT = 'rate-v3'
# kept for code written against the first release
PROMPT_VERSION, PROMPT, ASPECTS = 'rate-v2', PROMPT_V2, ('content', 'layout', 'color', 'style', 'text')

# score (rate-v3, the recommended total): SCORE_W_OVERALL * overall + (1 - SCORE_W_OVERALL) * overall_calc. The model's
# holistic `overall` is an integer and ties often (32% of pairs within a level); blending in the mean of the seven
# dimensions breaks almost all ties (2%) and agreed better with the reference judge (see README).
# overall_calc: plain mean of the non-null dimensions. A content cap (content <= 3 -> cap at content) was tried and dropped: it flattened the many
# different-brief pairs with low content scores and lowered agreement with the reference judge (see README).


# ---------------------------------------------------------------- request / response

@lru_cache(maxsize=4096)
def encode_image(src):
    """Path or http(s) URL -> data URL (long side <= MAX_SIDE, webp). URLs are fetched so both images are prepared identically."""
    if src.startswith(('http://', 'https://')):
        raw = httpx.get(src, timeout=60, follow_redirects=True).raise_for_status().content
        im = Image.open(io.BytesIO(raw))
    else:
        im = Image.open(src)
    im = im.convert('RGB'); im.thumbnail((MAX_SIDE, MAX_SIDE))
    buf = io.BytesIO(); im.save(buf, 'WEBP', quality=WEBP_QUALITY)
    return 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()


def request_body(image_a, image_b, model=DEFAULT_MODEL, effort='low', prompt='rate-v2'):
    """Responses API body (also usable verbatim as the `body` of a Batch API line).
    rate-v3: image_a is the REFERENCE, image_b the CANDIDATE. The default stays rate-v2 for backward compatibility;
    the CLI defaults to rate-v3."""
    img = lambda s: {'type': 'input_image', 'image_url': encode_image(s), 'detail': 'high'}
    if prompt == 'rate-v2':
        return {'model': model, 'reasoning': {'effort': effort}, 'max_output_tokens': 4000, 'store': False,
                'input': [{'role': 'developer', 'content': PROMPT_V2},
                          {'role': 'user', 'content': [{'type': 'input_text', 'text': 'Image 1:'}, img(image_a),
                                                       {'type': 'input_text', 'text': 'Image 2:'}, img(image_b)]}]}
    if prompt == 'rate-v3':
        return {'model': model, 'reasoning': {'effort': effort}, 'max_output_tokens': 6000, 'store': False,
                'text': {'format': SCHEMA_V3},
                'input': [{'role': 'developer', 'content': PROMPT_V3},
                          {'role': 'user', 'content': [{'type': 'input_text', 'text': 'REFERENCE:'}, img(image_a),
                                                       {'type': 'input_text', 'text': 'CANDIDATE:'}, img(image_b)]}]}
    raise ValueError(f'unknown prompt {prompt!r}; choose from {sorted(PROMPTS)}')


def output_text(body):
    return ''.join(c.get('text', '') for o in body.get('output', []) if o.get('type') == 'message'
                   for c in o.get('content', []) if c.get('type') == 'output_text')


def _json(text):
    t = text.strip().strip('`'); t = t[t.find('{'): t.rfind('}') + 1]
    return json.loads(t)


def _score(x, name, nullable):
    if x is None:
        if nullable: return None
        raise ValueError(f'missing {name}')
    x = float(x)
    if not 0 <= x <= 10: raise ValueError(f'{name} out of range: {x}')
    return x


def parse_scores(text):
    """rate-v2 model text -> {"overall", aspects..., "reason"}; raises ValueError if it is not the expected JSON."""
    v = _json(text)
    out = {k: _score(v.get(k), k, k == 'text') for k in ('overall',) + ASPECTS}
    out['reason'] = str(v.get('reason', ''))
    return out


SCORE_W_OVERALL = 0.5


def overall_calc(scores):
    xs = [scores[d] for d in DIMS_V3 if scores.get(d) is not None]
    return round(sum(xs) / len(xs), 3)


def parse_scores_v3(text):
    """rate-v3 model text -> {"score", "overall", "overall_calc", seven dims..., "justifications": {dim: str}}."""
    v = _json(text)
    out, why = {}, {}
    for d in DIMS_V3 + ('overall',):
        e = v.get(d)
        if not isinstance(e, dict): raise ValueError(f'missing {d}')
        out[d] = _score(e.get('score'), d, d in NULLABLE_V3); why[d] = str(e.get('justification', ''))
    out['overall_calc'] = overall_calc(out)
    out['score'] = round(SCORE_W_OVERALL * out['overall'] + (1 - SCORE_W_OVERALL) * out['overall_calc'], 3)
    out['justifications'] = why
    return out


def row_from_response(pid, body, model, prompt='rate-v2'):
    parse = parse_scores_v3 if prompt == 'rate-v3' else parse_scores
    return dict(pid=pid, **parse(output_text(body)), prompt=prompt, model=body.get('model', model), usage=body.get('usage'))


# ---------------------------------------------------------------- helpers

def api_key():
    k = os.environ.get('OPENAI_API_KEY')
    if not k and os.environ.get('OPENAI_API_KEY_FILE'): k = Path(os.environ['OPENAI_API_KEY_FILE']).expanduser().read_text().strip()
    if not k: sys.exit('set OPENAI_API_KEY (or OPENAI_API_KEY_FILE)')
    return k


def client():
    return httpx.Client(headers={'Authorization': f'Bearer {api_key()}'}, timeout=httpx.Timeout(600, connect=30))


def read_pairs(path):
    pairs, seen = [], set()
    for i, line in enumerate(open(path), 1):
        if not line.strip(): continue
        p = json.loads(line)
        for k in ('pid', 'image_a', 'image_b'):
            if k not in p: sys.exit(f'{path}:{i}: missing "{k}"')
        if p['pid'] in seen: sys.exit(f'{path}:{i}: duplicate pid {p["pid"]}')
        seen.add(p['pid']); pairs.append(p)
    return pairs


def done_pids(out):
    if not Path(out).exists(): return set()
    return {r['pid'] for r in map(json.loads, filter(str.strip, open(out))) if 'error' not in r}


# ---------------------------------------------------------------- online

def judge_one(cl, p, model, effort, prompt=DEFAULT_PROMPT, retries=5):
    err = None
    for attempt in range(retries):
        try:
            r = cl.post(f'{API}/responses', json=request_body(p['image_a'], p['image_b'], model, effort, prompt))
            if r.status_code in (429, 500, 502, 503, 504): raise RuntimeError(f'HTTP {r.status_code}')
            r.raise_for_status()
            return row_from_response(p['pid'], r.json(), model, prompt)
        except (httpx.HTTPError, RuntimeError, ValueError, json.JSONDecodeError) as e:
            err = f'{type(e).__name__}: {e}'[:300]; time.sleep(min(60, 2 ** attempt * 2))
    return dict(pid=p['pid'], error=err, prompt=prompt, model=model)


def cmd_run(a):
    pairs = read_pairs(a.pairs); skip = done_pids(a.out); todo = [p for p in pairs if p['pid'] not in skip]
    print(f'{len(pairs)} pairs, {len(skip)} already done, {len(todo)} to judge with {a.model} (effort {a.effort}, prompt {a.prompt})', file=sys.stderr)
    if a.dry_run:
        b = json.dumps(request_body(todo[0]['image_a'], todo[0]['image_b'], a.model, a.effort, a.prompt)) if todo else ''
        print(f'dry run: first request body is {len(b) / 1024:.0f} KB; no API calls made', file=sys.stderr); return
    lock, n_ok, n_err = threading.Lock(), 0, 0
    with client() as cl, open(a.out, 'a') as f, cf.ThreadPoolExecutor(a.concurrency) as ex:
        for row in ex.map(lambda p: judge_one(cl, p, a.model, a.effort, a.prompt), todo):
            with lock:
                f.write(json.dumps(row, ensure_ascii=False) + '\n'); f.flush()
                n_err += 'error' in row; n_ok += 'error' not in row
                if (n_ok + n_err) % 50 == 0: print(f'  {n_ok + n_err}/{len(todo)} (errors {n_err})', file=sys.stderr)
    print(f'done: {n_ok} ok, {n_err} errors -> {a.out}' + (' (re-run to retry errors)' if n_err else ''), file=sys.stderr)


# ---------------------------------------------------------------- batch

def _state(work):
    p = Path(work) / 'state.json'
    return p, (json.loads(p.read_text()) if p.exists() else {})


def cmd_batch_build(a):
    work = Path(a.work); (work / 'in').mkdir(parents=True, exist_ok=True)
    sp, st = _state(work)
    if st: sys.exit(f'{sp} exists; use a fresh work dir')
    meta, buf, size, shard = {}, [], 0, 0
    def flush():
        nonlocal buf, size, shard
        if not buf: return
        name = f'shard-{shard:03d}'; (work / 'in' / f'{name}.jsonl').write_text(''.join(buf))
        st[name] = dict(n=len(buf), bytes=size, status='built'); shard += 1; buf, size = [], 0
    for p in read_pairs(a.pairs):
        line = json.dumps({'custom_id': p['pid'], 'method': 'POST', 'url': '/v1/responses',
                           'body': request_body(p['image_a'], p['image_b'], a.model, a.effort, a.prompt)}) + '\n'
        if size + len(line) > MAX_SHARD_BYTES: flush()
        buf.append(line); size += len(line); meta[p['pid']] = a.model
    flush(); sp.write_text(json.dumps(st, indent=1)); (work / 'meta.json').write_text(json.dumps({'prompt': a.prompt, 'model': a.model, 'effort': a.effort}))
    print(f'{len(meta)} requests in {len(st)} shards under {work}/in; next: batch-submit {work}', file=sys.stderr)


def cmd_batch_submit(a):
    sp, st = _state(a.work); work = Path(a.work)
    with client() as cl:
        for name, s in st.items():
            if s['status'] != 'built': continue
            with open(work / 'in' / f'{name}.jsonl', 'rb') as fh:
                fid = cl.post(f'{API}/files', data={'purpose': 'batch'}, files={'file': (f'{name}.jsonl', fh, 'application/jsonl')}).raise_for_status().json()['id']
            bid = cl.post(f'{API}/batches', json={'input_file_id': fid, 'endpoint': '/v1/responses',
                                                  'completion_window': '24h'}).raise_for_status().json()['id']
            s.update(status='submitted', file_id=fid, batch_id=bid); sp.write_text(json.dumps(st, indent=1))
            print(f'{name}: {bid}', file=sys.stderr)


def cmd_batch_poll(a):
    sp, st = _state(a.work); work = Path(a.work); (work / 'out').mkdir(exist_ok=True)
    with client() as cl:
        for name, s in st.items():
            if s['status'] != 'submitted': continue
            b = cl.get(f"{API}/batches/{s['batch_id']}").raise_for_status().json()
            c = b.get('request_counts', {})
            print(f"{name}: {b['status']} {c.get('completed', 0)}/{c.get('total', '?')} failed {c.get('failed', 0)}", file=sys.stderr)
            if b['status'] in ('completed', 'expired', 'cancelled', 'failed'):
                for key, suffix in (('output_file_id', ''), ('error_file_id', '.errors')):
                    if b.get(key):
                        (work / 'out' / f'{name}{suffix}.jsonl').write_bytes(cl.get(f"{API}/files/{b[key]}/content").raise_for_status().content)
                s['status'] = 'done:' + b['status']; sp.write_text(json.dumps(st, indent=1))


def cmd_batch_collect(a):
    work = Path(a.work); n_ok = n_err = 0
    mp = work / 'meta.json'; prompt = json.loads(mp.read_text())['prompt'] if mp.exists() else 'rate-v2'
    with open(a.out, 'w') as f:
        for fp in sorted((work / 'out').glob('*.jsonl')):
            for line in filter(str.strip, open(fp)):
                r = json.loads(line); pid = r['custom_id']; resp = r.get('response') or {}
                try:
                    if r.get('error') or resp.get('status_code') != 200: raise ValueError(str(r.get('error') or resp.get('status_code')))
                    row = row_from_response(pid, resp['body'], resp['body'].get('model'), prompt); n_ok += 1
                except (ValueError, KeyError, json.JSONDecodeError) as e:
                    row = dict(pid=pid, error=f'{type(e).__name__}: {e}'[:300], prompt=prompt); n_err += 1
                f.write(json.dumps(row, ensure_ascii=False) + '\n')
    print(f'{n_ok} ok, {n_err} errors -> {a.out} (judge the errors again with `run`, it skips pids that are already ok)', file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    def model_args(p):
        p.add_argument('--model', default=DEFAULT_MODEL); p.add_argument('--effort', default='low')
        p.add_argument('--prompt', default=DEFAULT_PROMPT, choices=sorted(PROMPTS))
    p = sub.add_parser('run'); p.add_argument('pairs'); p.add_argument('out'); model_args(p)
    p.add_argument('--concurrency', type=int, default=16); p.add_argument('--dry-run', action='store_true'); p.set_defaults(f=cmd_run)
    p = sub.add_parser('batch-build'); p.add_argument('pairs'); p.add_argument('work'); model_args(p); p.set_defaults(f=cmd_batch_build)
    for name, fn in (('batch-submit', cmd_batch_submit), ('batch-poll', cmd_batch_poll)):
        p = sub.add_parser(name); p.add_argument('work'); p.set_defaults(f=fn)
    p = sub.add_parser('batch-collect'); p.add_argument('work'); p.add_argument('out'); p.set_defaults(f=cmd_batch_collect)
    a = ap.parse_args(); a.f(a)


if __name__ == '__main__':
    main()
